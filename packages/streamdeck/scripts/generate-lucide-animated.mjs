import {
  mkdir,
  mkdtemp,
  readFile,
  readdir,
  rm,
  writeFile,
} from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { build } from "esbuild";
import { chromium } from "playwright";

const execFileAsync = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const workspaceRoot = path.resolve(root, "../..");
const outputPath = path.join(root, "src/render/lucide-animated.generated.ts");
const inspectorOutputPath = path.join(
  root,
  "co.laikasoft.stonemite.sdPlugin/ui/lucide-animated-icons.generated.js",
);
const pinnedCommit = "61c4202489f898cccaa2aa64b6a2d5a1a713a32e";
const providedSource = process.argv.includes("--source")
  ? process.argv[process.argv.indexOf("--source") + 1]
  : process.env.LUCIDE_ANIMATED_SOURCE;
const temporaryRoot = await mkdtemp(
  path.join(os.tmpdir(), "streamdeck-lucide-"),
);

try {
  const sourceRoot = providedSource
    ? path.resolve(providedSource)
    : await checkoutPinnedSource(temporaryRoot);
  const { stdout: sourceCommit } = await execFileAsync("git", [
    "-C",
    sourceRoot,
    "rev-parse",
    "HEAD",
  ]);
  if (sourceCommit.trim() !== pinnedCommit) {
    throw new Error(
      `Lucide Animated source is ${sourceCommit.trim()}, expected ${pinnedCommit}.`,
    );
  }
  const iconRoot = path.join(sourceRoot, "icons");
  const icons = await discoverIcons(iconRoot, temporaryRoot);
  const entryPath = path.join(temporaryRoot, "entry.tsx");
  const utilityStubPath = path.join(temporaryRoot, "utils.js");
  const bundlePath = path.join(temporaryRoot, "bundle.js");
  const htmlPath = path.join(temporaryRoot, "index.html");

  await writeFile(entryPath, browserEntry(icons), "utf8");
  await writeFile(
    utilityStubPath,
    'export const cn = (...values) => values.filter(Boolean).join(" ");\n',
    "utf8",
  );
  await build({
    entryPoints: [entryPath],
    outfile: bundlePath,
    bundle: true,
    format: "iife",
    platform: "browser",
    jsx: "automatic",
    alias: { "@/lib/utils": utilityStubPath, "@": sourceRoot },
    nodePaths: [
      path.join(root, "node_modules"),
      path.join(workspaceRoot, "node_modules"),
    ],
    logLevel: "warning",
  });
  await writeFile(
    htmlPath,
    '<!doctype html><html><body><div id="root"></div><script src="bundle.js"></script></body></html>',
    "utf8",
  );

  const catalog = await captureCatalog(htmlPath, icons);
  const generated = `/* eslint-disable */\n// Generated by scripts/generate-lucide-animated.mjs from Lucide Animated (MIT), commit ${pinnedCommit}.\n// The complete license ships in co.laikasoft.stonemite.sdPlugin/THIRD_PARTY_NOTICES.md.\nexport const LUCIDE_ANIMATED_COMMIT = ${JSON.stringify(pinnedCommit)} as const;\nexport const LUCIDE_ANIMATED_ICONS = ${JSON.stringify(catalog)} as const;\nexport type LucideAnimatedIcon = keyof typeof LUCIDE_ANIMATED_ICONS;\n`;
  await writeFile(outputPath, generated, "utf8");
  await writeFile(
    inspectorOutputPath,
    `// Generated from Lucide Animated (MIT), commit ${pinnedCommit}. See THIRD_PARTY_NOTICES.md.\nwindow.STONEMITE_LUCIDE_ANIMATED_ICONS = ${JSON.stringify(catalog)};\n`,
    "utf8",
  );
  console.log(
    `Generated ${path.relative(root, outputPath)} and property-inspector previews with ${icons.length} Lucide Animated icons.`,
  );
} finally {
  await rm(temporaryRoot, { recursive: true, force: true });
}

async function checkoutPinnedSource(temporaryRoot) {
  const checkout = path.join(temporaryRoot, "source");
  await execFileAsync("git", ["init", "--quiet", checkout]);
  await execFileAsync(
    "git",
    [
      "-C",
      checkout,
      "fetch",
      "--quiet",
      "--depth=1",
      "https://github.com/pqoqubbw/icons.git",
      pinnedCommit,
    ],
    { maxBuffer: 1024 * 1024 },
  );
  await execFileAsync("git", [
    "-C",
    checkout,
    "checkout",
    "--quiet",
    "FETCH_HEAD",
  ]);
  return checkout;
}

async function discoverIcons(iconRoot, temporaryRoot) {
  const icons = [];
  const patchedRoot = path.join(temporaryRoot, "patched-icons");
  await mkdir(patchedRoot, { recursive: true });
  for (const filename of (await readdir(iconRoot)).sort()) {
    if (!filename.endsWith(".tsx")) continue;
    const originalPath = path.join(iconRoot, filename);
    const source = await readFile(originalPath, "utf8");
    const localComponent = source.match(/([A-Za-z0-9_]+)\.displayName =/u)?.[1];
    const exported =
      source.match(
        /export \{ (?:[A-Za-z0-9_]+ as )?([A-Za-z0-9]+Icon) \};/u,
      )?.[1] ??
      (localComponent && source.includes(`export const ${localComponent}`)
        ? localComponent
        : undefined);
    const component = exported ?? localComponent;
    if (!component || !localComponent)
      throw new Error(`Could not find the icon component name in ${filename}.`);
    let iconPath = originalPath;
    if (!exported) {
      iconPath = path.join(patchedRoot, filename);
      await writeFile(
        iconPath,
        `${source}\nexport { ${localComponent} as ${component} };\n`,
        "utf8",
      );
    }
    icons.push({
      component,
      path: iconPath,
      slug: filename.slice(0, -4),
    });
  }
  return icons;
}

function browserEntry(icons) {
  const imports = icons
    .map(
      ({ component, path: iconPath }, index) =>
        `import { ${component} as Icon${index} } from ${JSON.stringify(iconPath)};`,
    )
    .join("\n");
  const entries = icons
    .map(
      ({ slug }, index) =>
        `{ slug: ${JSON.stringify(slug)}, Component: Icon${index} }`,
    )
    .join(",\n");
  return `import React, { createRef } from "react";
import { createRoot } from "react-dom/client";
${imports}
const icons = [${entries}];
const refs = new Map();
function App() {
  return React.createElement(
    React.Fragment,
    null,
    ...icons.map(({ slug, Component }) => {
      const ref = createRef();
      refs.set(slug, ref);
      return React.createElement("div", { key: slug, "data-icon-slug": slug }, React.createElement(Component, { ref, size: 24 }));
    }),
  );
}
createRoot(document.getElementById("root")).render(React.createElement(App));
window.streamdeckIcons = {
  ready: () => icons.every(({ slug }) => document.querySelector('[data-icon-slug="' + slug + '"] svg')),
  start: () => { for (const ref of refs.values()) ref.current?.startAnimation?.(); },
  sample: () => Object.fromEntries(icons.map(({ slug }) => [slug, document.querySelector('[data-icon-slug="' + slug + '"] svg').outerHTML])),
};
`;
}

async function captureCatalog(htmlPath, icons) {
  const browser = await chromium.launch({
    headless: true,
    ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE
      ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE }
      : {}),
  });
  try {
    const page = await browser.newPage();
    await page.goto(`file://${htmlPath}`);
    await page.waitForFunction(() => window.streamdeckIcons?.ready());
    await page.waitForTimeout(100);
    const normal = await page.evaluate(() => window.streamdeckIcons.sample());
    await page.evaluate(() => window.streamdeckIcons.start());
    const sampleTimes = [0, 150, 300, 450, 600, 750, 950, 1250];
    const frames = Object.fromEntries(icons.map(({ slug }) => [slug, []]));
    let elapsed = 0;
    for (const target of sampleTimes) {
      await page.waitForTimeout(target - elapsed);
      elapsed = target;
      const sample = await page.evaluate(() => window.streamdeckIcons.sample());
      for (const { slug } of icons) frames[slug].push(sample[slug]);
    }
    return Object.fromEntries(
      icons.map(({ slug }) => [
        slug,
        { normal: normal[slug], frames: frames[slug] },
      ]),
    );
  } finally {
    await browser.close();
  }
}
